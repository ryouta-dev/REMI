CREATE TABLE IF NOT EXISTS staff (
  id INT AUTO_INCREMENT PRIMARY KEY, login VARCHAR(32) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL, role ENUM('admin','waiter') NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE, auth_version INT NOT NULL DEFAULT 1,
  telegram_id BIGINT UNIQUE, link_hash CHAR(64) UNIQUE, link_expires DATETIME
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS categories (
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0, published BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS dishes (
  id INT AUTO_INCREMENT PRIMARY KEY, category_id INT NOT NULL, name VARCHAR(160) NOT NULL,
  description TEXT NOT NULL, image VARCHAR(255), sort_order INT NOT NULL DEFAULT 0,
  available BOOLEAN NOT NULL DEFAULT TRUE, published BOOLEAN NOT NULL DEFAULT TRUE,
  FOREIGN KEY (category_id) REFERENCES categories(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS variants (
  id INT AUTO_INCREMENT PRIMARY KEY, dish_id INT NOT NULL, label VARCHAR(100) NOT NULL,
  price INT UNSIGNED NOT NULL, available BOOLEAN NOT NULL DEFAULT TRUE,
  FOREIGN KEY (dish_id) REFERENCES dishes(id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS dining_tables (
  id INT AUTO_INCREMENT PRIMARY KEY, label VARCHAR(80) NOT NULL UNIQUE,
  qr_token CHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  generation INT NOT NULL DEFAULT 1, enabled BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS visits (
  id INT AUTO_INCREMENT PRIMARY KEY, table_id INT NOT NULL,
  opened_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, closed_at DATETIME,
  active_table INT AS (IF(closed_at IS NULL, table_id, NULL)) PERSISTENT UNIQUE,
  FOREIGN KEY (table_id) REFERENCES dining_tables(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS orders (
  id INT AUTO_INCREMENT PRIMARY KEY, visit_id INT NOT NULL, guest CHAR(64) NOT NULL,
  request_key CHAR(36) NOT NULL, status ENUM('pending','cooking','served','rejected','cancelled') NOT NULL DEFAULT 'pending',
  version INT NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  telegram_message BIGINT, notify_due DATETIME, notified_at DATETIME,
  UNIQUE (guest, request_key), INDEX (status, notify_due), INDEX (visit_id, status),
  FOREIGN KEY (visit_id) REFERENCES visits(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS order_lines (
  id INT AUTO_INCREMENT PRIMARY KEY, order_id INT NOT NULL, variant_id INT NOT NULL,
  name VARCHAR(265) NOT NULL, price INT UNSIGNED NOT NULL,
  quantity INT UNSIGNED NOT NULL, cancelled INT UNSIGNED NOT NULL DEFAULT 0,
  FOREIGN KEY (order_id) REFERENCES orders(id), FOREIGN KEY (variant_id) REFERENCES variants(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS staff_events (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, staff_id INT NOT NULL, order_id INT, visit_id INT,
  action VARCHAR(40) NOT NULL, detail TEXT, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (staff_id) REFERENCES staff(id), FOREIGN KEY (order_id) REFERENCES orders(id),
  FOREIGN KEY (visit_id) REFERENCES visits(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS attempts (
  bucket CHAR(64) PRIMARY KEY, window_id INT UNSIGNED NOT NULL, hits INT UNSIGNED NOT NULL,
  INDEX (window_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS telegram_updates (
  id BIGINT PRIMARY KEY, processed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (processed_at)
) ENGINE=InnoDB;
